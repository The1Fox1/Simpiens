    /// <summary>
    /// A 5x7 pixel font for ASCII 32 to 126 (Epic CLIENT M1.2), generated in code like the rest of the art: map labels,
    /// "UNCHARTED", crawler names. Each glyph is a <see cref="PixelSprite"/> (white; tinted when drawn) in the font's own
    /// sheet. Glyphs advance <see cref="Advance"/> pixels: five wide plus one of spacing. Unknown characters draw as '?'.
    /// The UI's real fonts arrive with Gum (M2).
    /// </summary>
    public static class PixelFont
    {
        public const int GlyphWidth = 5;
        public const int GlyphHeight = 7;
        public const int Advance = GlyphWidth + 1;
        public const char First = ' ';
        public const char Last = '~';

        private static readonly PixelSprite[] _glyphs;

        // Built here, after every field initializer has run (Rows is declared below)
        static PixelFont() => _glyphs = Build();

        /// <summary>Every glyph, from <see cref="First"/> to <see cref="Last"/>; a glyph's index is its place here.</summary>
        public static PixelSprite[] Glyphs => _glyphs;

        public static PixelSprite Glyph(char c) => c >= First && c <= Last ? _glyphs[c - First] : _glyphs['?' - First];

        /// <summary>The width of <paramref name="text"/> in font pixels (no trailing space after the last glyph).</summary>
        public static int MeasurePixels(string text) => string.IsNullOrEmpty(text) ? 0 : text.Length * Advance - 1;

        private static PixelSprite[] Build()
        {
            var white = new Rgba32(255, 255, 255, 255);
            var glyphs = new PixelSprite[Rows.Length];
            for (int g = 0; g < Rows.Length; g++)
            {
                var rows = Rows[g].Split('|');
                var pixels = new Rgba32[GlyphWidth * GlyphHeight];
                for (int y = 0; y < GlyphHeight; y++)
                {
                    for (int x = 0; x < GlyphWidth; x++) pixels[y * GlyphWidth + x] = rows[y][x] == '#' ? white : Rgba32.Clear;
                }
                glyphs[g] = new PixelSprite(g, "Glyph_" + (char)(First + g), GlyphWidth, GlyphHeight, pixels);
            }
            return glyphs;
        }

